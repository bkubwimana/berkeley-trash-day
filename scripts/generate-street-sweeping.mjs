import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SOURCES = Object.freeze({
  "a-g": {
    flag: "--a-g",
    name: "Street Names A–G",
    url: "https://berkeleyca.gov/sites/default/files/2022-03/StreetSweepingSchedule_StNamesA-G.pdf"
  },
  "h-z": {
    flag: "--h-z",
    name: "Street Names H–Z",
    url: "https://berkeleyca.gov/sites/default/files/2022-03/StreetSweepingSchedule_StNamesH-Z.pdf"
  },
  numbered: {
    flag: "--numbered",
    name: "Numbered Streets",
    url: "https://berkeleyca.gov/sites/default/files/2022-03/StreetSweepingSchedule_StNumbered.pdf"
  }
});

const WEEKDAYS = Object.freeze({ Mon: "Monday", Tue: "Tuesday", Wed: "Wednesday", Thurs: "Thursday", Fri: "Friday" });

function argumentValue(flag) {
  const index = process.argv.indexOf(flag);
  if (index < 0 || !process.argv[index + 1]) throw new Error(`Missing required ${flag} PDF path.`);
  return resolve(process.argv[index + 1]);
}

function normalizeOptOut(value = "") {
  return value.split("/").filter(Boolean).map((part) => {
    const number = Number(part);
    return number < 100 ? number * 100 : number;
  });
}

function parseLine(line, source) {
  const columns = line.trim().split(/\s{2,}/);
  if (!/^\d+$/.test(columns[0] ?? "")) return null;

  if (/^\d+(?:st|nd|rd|th)(?:Mon|Tue|Wed|Thurs|Fri)$/.test(columns[5] ?? "")) {
    columns[5] = columns[5].replace(/(st|nd|rd|th)(?=[A-Z])/, "$1 ");
  }

  let [route, streetName, side, addressFrom, addressTo, schedule, period, fromStreet, toStreet, optOut = ""] = columns;
  if (/^\d+(?:st|nd|rd|th) (?:Mon|Tue|Wed|Thurs|Fri)$/.test(addressTo ?? "")) {
    optOut = "";
    toStreet = fromStreet;
    fromStreet = period;
    period = schedule;
    schedule = addressTo;
    addressTo = addressFrom;
  }

  const scheduleMatch = schedule?.match(/^(\d)(?:st|nd|rd|th) (Mon|Tue|Wed|Thurs|Fri)$/);
  if (
    !scheduleMatch ||
    !/^(N|S|E|W|N\/S|S\/N|E\/W|W\/E)$/.test(side ?? "") ||
    !/^\d+$/.test(addressFrom ?? "") ||
    !/^\d+$/.test(addressTo ?? "") ||
    !/^(AM|PM)$/.test(period ?? "")
  ) return null;

  return {
    source,
    route: Number(route),
    streetName,
    side,
    addressFrom: Number(addressFrom),
    addressTo: Number(addressTo),
    ordinal: Number(scheduleMatch[1]),
    weekday: WEEKDAYS[scheduleMatch[2]],
    period,
    fromStreet,
    toStreet,
    optOutBlocks: normalizeOptOut(optOut)
  };
}

const rows = [];
for (const [source, metadata] of Object.entries(SOURCES)) {
  const pdfPath = argumentValue(metadata.flag);
  const text = execFileSync("pdftotext", ["-layout", pdfPath, "-"], { encoding: "utf8", maxBuffer: 10_000_000 });
  for (const line of text.split(/\r?\n/)) {
    const row = parseLine(line, source);
    if (row) rows.push(row);
  }
}

if (rows.length < 700) throw new Error(`Only ${rows.length} rows parsed; expected at least 700. Refusing to write partial data.`);

rows.sort((a, b) => a.streetName.localeCompare(b.streetName) || a.addressFrom - b.addressFrom || a.side.localeCompare(b.side));
const output = `// Generated by scripts/generate-street-sweeping.mjs. Do not edit by hand.\n\nexport const STREET_SWEEPING_METADATA = Object.freeze(${JSON.stringify({
  sourceName: "City of Berkeley residential street-sweeping schedules",
  sourcePageUrl: "https://berkeleyca.gov/city-services/streets-sidewalks-sewers-and-utilities/street-sweeping",
  sourceDocuments: Object.fromEntries(Object.entries(SOURCES).map(([key, value]) => [key, { name: value.name, url: value.url }])),
  retrievedOn: "2026-09-14",
  rowCount: rows.length
}, null, 2)});\n\nexport const STREET_SWEEPING_ROWS = Object.freeze(${JSON.stringify(rows, null, 2)});\n`;

const outputPath = resolve("src/street-sweeping.generated.mjs");
writeFileSync(outputPath, output);
console.log(`Wrote ${rows.length} official schedule rows to ${outputPath}`);
